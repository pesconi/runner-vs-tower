    /// <summary>
    /// The economy table for the price decision (RT-5, D19): a simulated player plays the catalog's worlds in
    /// order with the real rules of <see cref="Progression"/> (rewards, stars, loops, unlocks) and buys the
    /// cheapest thing it can afford, upgrades first. The play assumptions are estimates [I] (no analytics yet,
    /// D4): they are printed with the table and are the first thing to replace with measured numbers.
    /// Batchmode: -executeMethod Claybreak.Editor.EconomyReport.WriteAndQuit [-claybreakReport docs/rt5-economia.md]
    /// </summary>
    public static class EconomyReport
    {
        public const string DefaultPath = "docs/rt6-economia.md";

        /// <summary>Play assumptions [I]; see the class summary.</summary>
        public struct Assumptions
        {
            /// <summary>Assault, result and menu after the run, on a win (s); the run itself is the level's course over its speed.</summary>
            public float secondsAfterRunWin;
            /// <summary>The same on a loss (s).</summary>
            public float secondsAfterRunLoss;
            public float winRate;
            public int armyAtLine;
            public float survivorShare;
            public int maximumLevels;

            public static Assumptions Default => new Assumptions
            {
                // Up to RT-6t.14 a win was 55 s and a loss 35 s in all, run included; the runs then averaged ~16 s
                // (course over speed), so the rest is kept: the run time now follows each level's speed (RT-6t.15).
                secondsAfterRunWin = LevelGenerator.SecondsAfterRun,
                secondsAfterRunLoss = 19f,
                winRate = 0.8f,
                armyAtLine = 60,
                survivorShare = 0.4f,  // 2 stars on average
                maximumLevels = 2000
            };
        }

        public readonly struct Purchase
        {
            public Purchase(string item, int price, int levels, float minutes, int loop)
            {
                Item = item;
                Price = price;
                Levels = levels;
                Minutes = minutes;
                Loop = loop;
            }

            public string Item { get; }
            public int Price { get; }
            public int Levels { get; }
            public float Minutes { get; }
            public int Loop { get; }
        }

        [MenuItem("Claybreak/Write Economy Report")]
        public static void WriteFromMenu()
        {
            Write(DefaultPath);
        }

        public static void WriteAndQuit()
        {
            BatchRunner.Run("EconomyReport", () => Write(BatchRunner.GetArgument("-claybreakReport") ?? DefaultPath));
        }

        public static void Write(string path)
        {
            var catalog = AssetDatabase.LoadAssetAtPath<ClaybreakCatalog>(WorldContent.CatalogPath)
                ?? throw new System.InvalidOperationException("Missing " + WorldContent.CatalogPath);
            Assumptions assumptions = Assumptions.Default;
            List<Purchase> purchases = Simulate(catalog, assumptions, out float coinsPerMinute, out List<Purchase> worlds,
                out float averageRun);
            // LF on every machine: the file is versioned and regenerated by the check script.
            string markdown = (Markdown(catalog, assumptions, purchases, coinsPerMinute, worlds, averageRun) + Levels(catalog))
                .Replace("\r\n", "\n");
            File.WriteAllText(path, markdown, new UTF8Encoding(false));
            Debug.Log($"[EconomyReport] {purchases.Count} purchases written to {path}.");
        }

        /// <summary>Plays until everything is bought (or the level cap); returns each purchase in order.</summary>
        public static List<Purchase> Simulate(ClaybreakCatalog catalog, Assumptions assumptions, out float coinsPerMinute) =>
            Simulate(catalog, assumptions, out coinsPerMinute, out _);

        /// <summary>Also returns, per world, when its first pass ended (Item = world id, Price = coins held then).</summary>
        public static List<Purchase> Simulate(ClaybreakCatalog catalog, Assumptions assumptions, out float coinsPerMinute,
            out List<Purchase> worldsCleared) =>
            Simulate(catalog, assumptions, out coinsPerMinute, out worldsCleared, out _);

        /// <summary>Also returns the average run of the levels played (s).</summary>
        public static List<Purchase> Simulate(ClaybreakCatalog catalog, Assumptions assumptions, out float coinsPerMinute,
            out List<Purchase> worldsCleared, out float averageRunSeconds)
        {
            worldsCleared = new List<Purchase>();
            var progression = new Progression(catalog, new SaveData());
            var purchases = new List<Purchase>();
            float seconds = 0f;
            float runSeconds = 0f;
            long earned = 0;
            float winDebt = 0f;
            int levels = 0;
            while (levels < assumptions.maximumLevels && !EverythingBought(progression))
            {
                // Deterministic win rate: a loss whenever the running share of wins would pass the rate.
                winDebt += assumptions.winRate;
                bool won = winDebt >= 1f;
                winDebt -= won ? 1f : 0f;
                int left = Mathf.RoundToInt(assumptions.armyAtLine * assumptions.survivorShare);
                string world = progression.World.WorldId;
                ClaybreakLevel level = progression.CurrentLevel;
                float run = RunPace.RunSeconds(level.FiringLineZ, level.RunSpeed);
                bool firstPass = progression.WorldProgress.loop == 0;
                LevelOutcome outcome = progression.Complete(won, assumptions.armyAtLine, won ? left : 0);
                earned += outcome.Coins;
                seconds += run + (won ? assumptions.secondsAfterRunWin : assumptions.secondsAfterRunLoss);
                runSeconds += run;
                levels++;
                if (outcome.ClearedWorld && firstPass)
                {
                    worldsCleared.Add(new Purchase(world, (int)earned, levels, seconds / 60f, 1));
                }

                while (TryBuyCheapest(progression, out string item, out int price))
                {
                    purchases.Add(new Purchase(item, price, levels, seconds / 60f, progression.WorldProgress.loop));
                }
            }

            coinsPerMinute = seconds <= 0f ? 0f : earned / (seconds / 60f);
            averageRunSeconds = levels == 0 ? 0f : runSeconds / levels;
            return purchases;
        }

        private static bool EverythingBought(Progression progression)
        {
            ClaybreakCatalog catalog = progression.Catalog;
            for (int i = 0; i < catalog.Upgrades.Count; i++)
            {
                if (!progression.IsUpgradeMaxed(i))
                {
                    return false;
                }
            }

            for (int i = 0; i < catalog.Units.Count; i++)
            {
                if (!progression.IsUnitOwned(i))
                {
                    return false;
                }
            }

            for (int i = 0; i < catalog.Skins.Count; i++)
            {
                if (!progression.IsSkinOwned(i))
                {
                    return false;
                }
            }

            for (int i = 0; i < catalog.Shapes.Count; i++)
            {
                if (!progression.IsShapeOwned(i))
                {
                    return false;
                }
            }

            return true;
        }

        // Upgrades first (they make the game easier), then elites, then skins, then shapes (RT-6t.20); the cheapest of each kind.
        private static bool TryBuyCheapest(Progression progression, out string item, out int price)
        {
            ClaybreakCatalog catalog = progression.Catalog;
            int best = -1;
            int bestPrice = int.MaxValue;
            for (int i = 0; i < catalog.Upgrades.Count; i++)
            {
                if (!progression.IsUpgradeMaxed(i) && progression.NextUpgradeCost(i) < bestPrice)
                {
                    best = i;
                    bestPrice = progression.NextUpgradeCost(i);
                }
            }

            if (best >= 0)
            {
                item = $"{catalog.Upgrades[best].title} {progression.UpgradeLevel(best) + 1}";
                price = bestPrice;
                return progression.TryBuyUpgrade(best);
            }

            for (int i = 0; i < catalog.Units.Count; i++)
            {
                if (!progression.IsUnitOwned(i) && catalog.Units[i].price > 0)
                {
                    item = catalog.Units[i].title;
                    price = catalog.Units[i].price;
                    return progression.TryBuyUnit(i);
                }
            }

            for (int i = 0; i < catalog.Skins.Count; i++)
            {
                if (!progression.IsSkinOwned(i))
                {
                    item = "skin " + catalog.Skins[i].title;
                    price = catalog.Skins[i].price;
                    return progression.TryBuySkin(i);
                }
            }

            // RT-6t.20 (D32 A): the crowd shapes last, in catalog order (cheapest first).
            for (int i = 0; i < catalog.Shapes.Count; i++)
            {
                if (!progression.IsShapeOwned(i))
                {
                    item = "shape " + catalog.Shapes[i].title;
                    price = catalog.Shapes[i].price;
                    return progression.TryBuyShape(i);
                }
            }

            item = null;
            price = 0;
            return false;
        }

        private static string Markdown(ClaybreakCatalog catalog, Assumptions a, List<Purchase> purchases, float coinsPerMinute,
            List<Purchase> worlds, float averageRun)
        {
            CultureInfo pt = CultureInfo.GetCultureInfo("pt-BR");
            var text = new StringBuilder();
            text.AppendLine("# RT-6 — Economia simulada e fases (gerado por `EconomyReport`, não editar à mão)");
            text.AppendLine();
            text.AppendLine("Preços e curvas **[P]** do catálogo (`WorldContent.WriteCatalog`), jogados por um jogador simulado com as");
            text.AppendLine("regras reais (`Progression`). Premissas **[I]** (sem analytics ainda, D4):");
            text.AppendLine();
            text.AppendLine($"- corrida = pista até a linha de tiro ÷ velocidade da fase (ritmo x{RunPace.Factor.ToString("0.0#", pt)}, RT-6t.15; "
                + $"média {averageRun.ToString("0.0", pt)} s por fase jogada); depois dela, assalto + resultado em {a.secondsAfterRunWin:0} s "
                + $"na vitória e {a.secondsAfterRunLoss:0} s na derrota;");
            text.AppendLine($"- {a.winRate * 100f:0}% de vitórias; {a.armyAtLine} unidades na linha de tiro, {a.survivorShare * 100f:0}% sobrevivem (2 estrelas);");
            text.AppendLine($"- compra o mais barato que puder, upgrades antes de elites, skins e formas; joga os {catalog.Worlds.Count} mundos em ordem ({catalog.LevelCount} fases)");
            text.AppendLine("  e, depois do último, fica nas voltas dele (cada volta 25% mais forte e 25% mais rica).");
            text.AppendLine();
            text.AppendLine($"Média: **{coinsPerMinute.ToString("0", pt)} moedas por minuto** de jogo.");
            text.AppendLine();
            text.AppendLine("| Mundo | Primeira passada termina em | Fases jogadas | Moedas ganhas até ali |");
            text.AppendLine("|---|---|---|---|");
            foreach (Purchase w in worlds)
            {
                text.AppendLine($"| {w.Item} | {w.Minutes.ToString("0.0", pt)} min | {w.Levels} | {w.Price} |");
            }
            text.AppendLine();
            text.AppendLine("| # | Compra | Preço | Fases jogadas | Minutos de jogo | Volta do mundo |");
            text.AppendLine("|---|---|---|---|---|---|");
            for (int i = 0; i < purchases.Count; i++)
            {
                Purchase p = purchases[i];
                text.AppendLine($"| {i + 1} | {p.Item} | {p.Price} | {p.Levels} | {p.Minutes.ToString("0.0", pt)} | {p.Loop} |");
            }

            int total = 0;
            foreach (Purchase p in purchases)
            {
                total += p.Price;
            }

            Purchase last = purchases.Count > 0 ? purchases[purchases.Count - 1] : default;
            text.AppendLine();
            text.AppendLine($"Total: **{total} moedas**, tudo comprado em **{last.Minutes.ToString("0", pt)} minutos** ({last.Levels} fases).");
            text.AppendLine();
            text.AppendLine("## Sensibilidade");
            text.AppendLine();
            int shop = ShopTotal(catalog);
            for (int w = 0; w < catalog.Worlds.Count; w++)
            {
                int firstPass = FirstPassCoins(catalog, a, w);
                text.AppendLine($"- Primeira passada do {catalog.Worlds[w].world.WorldId} ({catalog.Worlds[w].world.LevelCount} fases, sem comprar): "
                    + $"**{firstPass} moedas** = {100f * firstPass / Mathf.Max(1, shop):0}% da loja ({shop}).");
            }
            foreach (float factor in new[] { 0.75f, 1.5f })
            {
                ClaybreakCatalog scaled = Scaled(catalog, factor);
                List<Purchase> run = Simulate(scaled, a, out _);
                Purchase end = run.Count > 0 ? run[run.Count - 1] : default;
                text.AppendLine($"- Preços x{factor.ToString("0.##", pt)}: tudo comprado em **{end.Minutes.ToString("0", pt)} minutos** ({end.Levels} fases, volta {end.Loop}).");
                UnityEngine.Object.DestroyImmediate(scaled);
            }

            text.AppendLine();
            text.AppendLine("Vieses conhecidos: a taxa de vitória e os sobreviventes não mudam com os upgrades nem com as voltas mais");
            text.AppendLine("fortes, e a renda futura de anúncio recompensado e recompensa diária (RT-7) não entra.");
            return text.ToString();
        }

        // Coins of one winning pass through world <paramref name="world"/> (first time), buying nothing.
        private static int FirstPassCoins(ClaybreakCatalog catalog, Assumptions a, int world)
        {
            var progression = new Progression(catalog, new SaveData());
            int left = Mathf.RoundToInt(a.armyAtLine * a.survivorShare);
            int coins = 0;
            for (int w = 0; w <= world; w++)
            {
                coins = progression.Save.coins;
                int levels = catalog.Worlds[w].world.LevelCount;
                for (int i = 0; i < levels; i++)
                {
                    progression.Complete(true, a.armyAtLine, left);
                }

                if (w < world && progression.WorldIndex != w + 1)
                {
                    // Stars short of the unlock: the simulated pass still counts the world's pay.
                    progression.Save.worlds[w + 1].loop = 0;
                    if (!progression.TrySelectWorld(w + 1))
                    {
                        return 0;
                    }
                }
            }

            return progression.Save.coins - coins;
        }

        private static int ShopTotal(ClaybreakCatalog catalog)
        {
            int total = 0;
            foreach (UpgradeTrack track in catalog.Upgrades)
            {
                foreach (UpgradeStep step in track.steps)
                {
                    total += step.cost;
                }
            }

            foreach (UnitType unit in catalog.Units)
            {
                total += unit.price;
            }

            foreach (CrowdSkin skin in catalog.Skins)
            {
                total += skin.price;
            }

            foreach (CrowdShapeOption shape in catalog.Shapes)
            {
                total += shape.price;
            }

            return total;
        }

        // Every level of every world as data: what the generator and the hand-made levels produced (RT-6).
        private static string Levels(ClaybreakCatalog catalog)
        {
            CultureInfo pt = CultureInfo.GetCultureInfo("pt-BR");
            var text = new StringBuilder();
            text.AppendLine();
            text.AppendLine("## Fases (dados gerados; vida antes das voltas)");
            text.AppendLine();
            text.AppendLine($"Potencial = exército no melhor caminho dos portões (teto {ArmyLimit.Units}) × melhor portão da fileira. Maior promessa = maior número que");
            text.AppendLine($"um portão da corrida pode mostrar em qualquer caminho, com as caixas (nunca passa de {ArmyLimit.Units}, RT-6t.14). Defesas: M muralha,");
            text.AppendLine("C canhão (intervalo, pedras), V varredor, E escudo (parte do dano que segura). Obstáculos (RT-6t.19): T tronco, S serra,");
            text.AppendLine("Ma martelo, B buraco, R rolo, com o ciclo em segundos. Perda esperada = parte do exército do melhor caminho que os obstáculos");
            text.AppendLine("matam até a linha de tiro (estimativa `ObstacleLoss` [I]: quem desvia lê o obstáculo e acerta o momento em ±0,3 s; quem");
            text.AppendLine("não desvia corre reto pelo meio); a vida da torre é calibrada sobre o exército de quem desvia.");
            foreach (WorldEntry entry in catalog.Worlds)
            {
                ClaybreakWorld world = entry.world;
                text.AppendLine();
                text.AppendLine($"### {world.WorldName} ({world.WorldId}) — paleta {(world.Look.palette == null ? "?" : world.Look.palette.name)}, {world.Look.trees} árvores e {world.Look.rocks} pedras, dano esperado x{world.ExpectedDamage:0.##}, abre com {entry.starsToUnlock} estrelas");
                text.AppendLine();
                text.AppendLine("| Fase | Torre | Andares | Vida | Início | Corrida | Maior promessa | Potencial | Obstáculos | Perda esperada (desvia / reto) | Defesas | Prêmio |");
                text.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|---|");
                foreach (ClaybreakLevel level in world.Levels)
                {
                    var spec = new LevelSpec
                    {
                        startCount = level.StartCount, runGates = Copy(level.RunGates), assaultGates = Copy(level.AssaultGates),
                        obstacles = Copy(level.Obstacles)
                    };
                    string defenses = (level.WallEnabled ? $"M{level.WallHealth} " : "")
                        + (level.CannonEnabled ? $"C{level.CannonInterval:0.0#}s/{level.MaximumProjectiles} " : "")
                        + (level.SweeperEnabled ? $"V{level.SweeperPeriod:0.0}s " : "")
                        + (level.ShieldEnabled ? $"E{level.ShieldHealth}/{level.ShieldBlock * 100f:0}% " : "");
                    string boss = level.IsBoss ? $" ({level.BossRule})" : string.Empty;
                    float run = RunPace.RunSeconds(level.FiringLineZ, level.RunSpeed);
                    text.AppendLine($"| {level.Title} | {level.Tower}{boss} | {level.Floors} | {level.TowerHealth} | {level.StartCount} | "
                        + $"{level.RunSpeed.ToString("0.##", pt)} m/s, {run.ToString("0.0", pt)} s | "
                        + $"{GateMath.HighestPromise(level.StartCount, level.RunGates, level.Crates, ArmyLimit.Units, out _)} | "
                        + $"{LevelGenerator.PotentialHits(spec, ArmyLimit.Units)} | {Obstacles(level, pt)} | {Loss(spec, level.RunSpeed, pt)} | "
                        + $"{defenses.Trim()} | {level.CoinReward} |");
                }
            }

            return text.ToString();
        }

        // RT-6t.19: the level's obstacles in run order, each with its cycle.
        private static string Obstacles(ClaybreakLevel level, CultureInfo pt)
        {
            if (level.Obstacles.Count == 0)
            {
                return "—";
            }

            var parts = new List<string>();
            foreach (ObstaclePlacement obstacle in level.Obstacles)
            {
                string name = obstacle.kind switch
                {
                    ObstacleKind.SwingingLog => "T",
                    ObstacleKind.Saw => "S",
                    ObstacleKind.Hammer => "Ma",
                    ObstacleKind.Hole => "B",
                    _ => "R"
                };
                parts.Add(ObstacleMotion.Moves(obstacle.kind) ? $"{name}{ObstacleMotion.Period(obstacle).ToString("0.0#", pt)}" : name);
            }

            return string.Join(" ", parts);
        }

        /// <summary>RT-6t.19: share of the best-path army the obstacles kill, for the player who dodges and the one who does not.</summary>
        public static float ExpectedLoss(LevelSpec spec, float runSpeed, bool dodging)
        {
            int best = LevelGenerator.BestArmy(spec, ArmyLimit.Units);
            return best <= 0 ? 0f : 1f - (float)LevelGenerator.ExpectedArmy(spec, ArmyLimit.Units, runSpeed, dodging) / best;
        }

        private static string Loss(LevelSpec spec, float runSpeed, CultureInfo pt)
        {
            if (spec.obstacles.Length == 0)
            {
                return "—";
            }

            return $"{(ExpectedLoss(spec, runSpeed, true) * 100f).ToString("0", pt)}% / {(ExpectedLoss(spec, runSpeed, false) * 100f).ToString("0", pt)}%";
        }

        private static T[] Copy<T>(IReadOnlyList<T> list)
        {
            var copy = new T[list.Count];
            for (int i = 0; i < copy.Length; i++)
            {
                copy[i] = list[i];
            }

            return copy;
        }

        // A copy of the catalog with every price multiplied (Instantiate copies the serialized lists).
        private static ClaybreakCatalog Scaled(ClaybreakCatalog catalog, float factor)
        {
            ClaybreakCatalog copy = UnityEngine.Object.Instantiate(catalog);
            foreach (UpgradeTrack track in copy.Upgrades)
            {
                for (int i = 0; i < track.steps.Length; i++)
                {
                    track.steps[i].cost = Mathf.RoundToInt(track.steps[i].cost * factor);
                }
            }

            foreach (UnitType unit in copy.Units)
            {
                unit.price = Mathf.RoundToInt(unit.price * factor);
            }

            foreach (CrowdSkin skin in copy.Skins)
            {
                skin.price = Mathf.RoundToInt(skin.price * factor);
            }

            return copy;
        }
    }
