"""Stampeep "wind-up toy" sound set (RT-6v3.9): ratchet, spring, short bell, burst into pieces, key winding, and the
four world run loops that share one four-note motif.

Own work, synthesized from math only (no samples, no third-party audio, nothing generated by an AI service: D37 = C).
Deterministic (fixed seeds). Built on the building blocks of clay_siege_audio.py, which imports this module and writes the
files; run that script, not this one:

    python Tools/audio/clay_siege_audio.py

The motif (docs/direcao-visual-v3.md, section 2.1): scale degrees 1 - 5 - 3 - 8 (up a fifth, back down to the third, up to
the octave: the sound of a key being wound and let go). Every world plays it on its own tonic, in its own mode and timbre.
"""
import numpy as np

import clay_siege_audio as base
from clay_siege_audio import (SR, TAU, bell, bandpass, brass, env_ad, env_adsr, highpass, hat, kick,
                              lowpass, midi, mix, noise, pluck, place, room, saw, shaker, snare, sweep_phase, t_axis, tri)

# ---------------------------------------------------------------- toy parts


def click(freq, seed, seconds=0.03, decay=140.0):
    """One tin tick of a ratchet: a band of noise plus a short ring at the pawl's pitch."""
    n = bandpass(noise(seconds, seed), freq * 0.6, freq * 1.8) * env_ad(seconds, 0.0005, decay)
    ring = np.sin(TAU * freq * t_axis(seconds)) * env_ad(seconds, 0.0005, decay * 0.7) * 0.5
    return n + ring


def ratchet(count, start_gap, end_gap, freq=3200.0, seed=300, rise=0.0):
    """A train of ticks whose spacing glides from start_gap to end_gap seconds (a wound spring letting go or a key being turned)."""
    gaps = np.linspace(start_gap, end_gap, count)
    total = float(np.sum(gaps)) + 0.06
    out = np.zeros(int(total * SR))
    at = 0.0
    for i, gap in enumerate(gaps):
        place(out, click(freq * (1.0 + rise * i / max(count - 1, 1)), seed + i), at, 0.9 if i % 2 == 0 else 0.7)
        at += gap
    return out


def spring_boing(f0=330.0, f1=150.0, seconds=0.5, wobble=38.0, decay=7.0):
    """A coil spring: a falling tone whose pitch wobbles fast and dies away (the 'boing' of a loosed spring)."""
    t = t_axis(seconds)
    f = f1 + (f0 - f1) * np.exp(-6.0 * t)
    f = f * (1.0 + 0.06 * np.sin(TAU * wobble * t) * np.exp(-3.0 * t))
    phase = TAU * np.cumsum(f) / SR
    body = np.sin(phase) + 0.35 * np.sin(2.01 * phase) + 0.15 * np.sin(3.02 * phase)
    return body * env_ad(seconds, 0.002, decay)


def short_bell(freq, seconds=0.28, decay=16.0):
    return bell(freq, seconds, decay)


def pieces_burst(seed, pieces=7, spread=0.16):
    """A toy popping into plastic pieces: a soft pop, then small hard ticks scattered at random, then a puff of confetti."""
    rng = np.random.default_rng(seed)
    seconds = spread + 0.12
    out = np.zeros(int(seconds * SR))
    pop = np.sin(sweep_phase(480.0, 170.0, 0.07, 2.0)) * env_ad(0.07, 0.001, 45.0)
    place(out, pop, 0.0, 0.7)
    for i in range(pieces):
        f = rng.uniform(1800.0, 5200.0)
        place(out, click(f, seed * 11 + i, 0.025, 160.0), rng.uniform(0.01, spread), rng.uniform(0.25, 0.55))
    confetti = highpass(noise(0.12, seed + 5), 6000.0) * env_ad(0.12, 0.004, 28.0)
    place(out, confetti, 0.03, 0.14)
    return out


def key_wind(turns=7):
    """The wind-up key turning once: ratchet ticks that slow down, a tin ring under them, ending on a tiny 'clunk'."""
    ticks = ratchet(turns, 0.045, 0.085, 2600.0, 410, rise=0.35)
    out = np.zeros(len(ticks) + int(0.12 * SR))
    place(out, ticks, 0.0, 1.0)
    clunk = np.sin(sweep_phase(260.0, 120.0, 0.09, 1.5)) * env_ad(0.09, 0.001, 38.0)
    place(out, clunk, len(ticks) / SR - 0.02, 0.7)
    return out


# ---------------------------------------------------------------- effects (kit roles and game cues)

def toy_coin():
    """Short bell pair (tink-tink)."""
    out = np.zeros(int(0.4 * SR))
    place(out, short_bell(midi(88), 0.2, 20.0), 0.0, 0.8)
    place(out, short_bell(midi(95), 0.3, 15.0), 0.07, 0.7)
    return out


def toy_gate_good():
    """Catraca: three ratchet ticks then the motif's first three notes on a short bell."""
    out = np.zeros(int(0.55 * SR))
    place(out, ratchet(3, 0.035, 0.035, 3400.0, 320), 0.0, 0.8)
    for i, n in enumerate([72, 79, 76]):
        place(out, short_bell(midi(n + 12), 0.25, 14.0), 0.1 + i * 0.07, 0.75)
    return out


def toy_gate_bad():
    """Mola: a coil spring loosening, falling."""
    return mix(spring_boing(), np.concatenate([np.zeros(int(0.03 * SR)), click(2200.0, 330) * 0.5]))


def toy_unit_loss():
    return pieces_burst(71, pieces=6, spread=0.12)


def toy_button_click():
    out = np.zeros(int(0.07 * SR))
    place(out, click(2800.0, 350, 0.04, 110.0), 0.0, 1.0)
    place(out, short_bell(midi(96), 0.06, 40.0), 0.004, 0.25)
    return out


def toy_button_back():
    out = np.zeros(int(0.09 * SR))
    place(out, click(2000.0, 351, 0.04, 100.0), 0.0, 1.0)
    place(out, short_bell(midi(84), 0.07, 38.0), 0.006, 0.25)
    return out


def toy_number_pop():
    """The number on a good gate jumping: a rising soft pop with a tiny bell, after a short rest (plays with the gate)."""
    seconds = 0.2
    out = np.zeros(int(seconds * SR))
    pop = np.sin(sweep_phase(300.0, 760.0, 0.09, 1.0)) * env_ad(0.09, 0.002, 30.0)
    place(out, pop, 0.07, 0.8)
    place(out, short_bell(midi(91), 0.12, 24.0), 0.12, 0.35)
    return out


def toy_key_wind():
    return key_wind()


