# ---------------------------------------------------------------- world music

MOTIF_MAJOR = (0, 7, 4, 12)  # degrees 1 - 5 - 3 - 8
MOTIF_MINOR = (0, 7, 3, 12)


def motif_notes(root, minor):
    return [root + s for s in (MOTIF_MINOR if minor else MOTIF_MAJOR)]


def _lead_bell(f):
    return mix(bell(f, 0.7, 5.0), pluck(f, 0.5, 1.0, 8.0) * 0.6)


def _lead_pluck(f):
    return pluck(f, 0.55, 1.6, 7.0)


def _lead_brass(f):
    return brass(f, 0.5, 2200.0, 0.03, 0.003) * 0.8


def _lead_square(f):
    ph = TAU * f * t_axis(0.45)
    return lowpass(base.square(ph, 6), 2600.0) * env_ad(0.45, 0.004, 6.0) * 0.55


# One entry per world: tonic (MIDI of the bass root), mode, bpm, chord roots over the tonic with a triad shape, lead timbre.
WORLDS = {
    "RunLoop": dict(tonic=48, minor=False, bpm=124, prog=[(0, 0), (9, 1), (5, 0), (7, 0)], lead=_lead_bell, swing=0.0),
    "RunLoopW2": dict(tonic=45, minor=True, bpm=132, prog=[(0, 1), (8, 0), (3, 0), (10, 0)], lead=_lead_pluck, swing=0.0),
    "RunLoopW3": dict(tonic=41, minor=False, bpm=112, prog=[(0, 0), (7, 0), (9, 1), (5, 0)], lead=_lead_brass, swing=0.16),
    "RunLoopW4": dict(tonic=50, minor=True, bpm=140, prog=[(0, 1), (5, 1), (8, 0), (7, 0)], lead=_lead_square, swing=0.0),
}


def world_music(spec):
    """Driving 8-bar loop: the world's chords, a kick/snare/hat bed, a bass line, a bell/pluck riff, and the motif every two bars."""
    bpm = spec["bpm"]
    tonic = spec["tonic"]
    beat = 60.0 / bpm
    voices = []
    notes = motif_notes(tonic + 24, spec["minor"])
    for bar in range(8):
        root_off, minor_triad = spec["prog"][bar % 4]
        root = tonic + root_off
        third = 3 if minor_triad else 4
        triad = [root + 12, root + 12 + third, root + 12 + 7]
        b0 = bar * 4
        for k in range(4):
            voices.append((b0 + k, kick(0.3, 150, 48), 0.7))
        voices.append((b0 + 1, snare(0.2, 21), 0.38))
        voices.append((b0 + 3, snare(0.2, 23), 0.38))
        for k in range(8):
            voices.append((b0 + k * 0.5 + (spec["swing"] * 0.5 if k % 2 else 0.0), hat(0.05, 31 + k % 4, k % 2 == 1),
                           0.09 if k % 2 else 0.06))
        for k, offset in enumerate([0, 0.75, 1.5, 2, 2.75, 3.5]):
            n = root + (7 if k in (2, 5) else 0)
            bs = lowpass(saw(TAU * midi(n) * t_axis(0.3), 10), 700.0) * env_ad(0.3, 0.003, 9.0)
            voices.append((b0 + offset, bs, 0.3))
        for k, step in enumerate([0, 12, 7, 12, third, 12, 7, 10]):
            voices.append((b0 + k * 0.5, pluck(midi(root + 24 + step), 0.25, 1.4, 14.0), 0.07))
        if bar % 2 == 0:
            for k, n in enumerate(notes):
                voices.append((b0 + k, spec["lead"](midi(n)), 0.3))
        if bar in (3, 7):
            for n in triad:
                voices.append((b0, brass(midi(n), 4 * beat * 0.95, 1800.0, 0.06), 0.06))
    loop = base.render_loop(8, bpm, 4, voices)
    return np.tanh(base.normalize(room(loop, 0.12, 0.7)[: len(loop)], -2.0) * 1.15)


WORLD_MUSIC = {name: (lambda spec=spec: world_music(spec)) for name, spec in WORLDS.items()}
